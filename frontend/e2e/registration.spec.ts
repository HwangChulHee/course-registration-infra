import { test, expect } from '@playwright/test';

test('가입 → 로그인 → 오픈/입장 → 신청/마감 → 새로고침/재로그인 → 취소',async({page,request})=>{
  const email=`browser-${Date.now()}@example.test`;
  const password=`Browser-${Date.now()}-Only`;
  await page.goto('/');
  await page.evaluate(()=>localStorage.setItem('campus-registration-demo-v1',JSON.stringify({currentUserId:'student-1',open:true,admitted:true,enrollments:[{courseId:'course-2'}]})));
  await page.reload();
  await expect(page.getByRole('heading',{name:'로그인',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'회원가입',exact:true}).click();
  await page.getByLabel('이름',{exact:true}).fill('브라우저검증');
  await page.getByLabel('이메일',{exact:true}).fill(email);
  await page.getByLabel('비밀번호',{exact:true}).fill(password);
  await page.getByRole('button',{name:'데모 회원가입',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('가입이 완료되었습니다');
  await page.getByRole('button',{name:'확인',exact:true}).click();
  async function login(loginEmail:string) {
    await page.getByLabel('이메일',{exact:true}).fill(loginEmail);
    await page.getByLabel('비밀번호',{exact:true}).fill(password);
    await page.getByRole('button',{name:'로그인 →',exact:true}).click();
    await expect(page.getByRole('button',{name:'수강신청 입장 →'})).toBeVisible();
    await expect(page.getByRole('dialog')).not.toBeVisible();
  }
  await login(email);
  await page.getByText('개발자용 시연 설정',{exact:true}).click();
  const closeWindow=page.getByRole('button',{name:'오픈 전으로 변경',exact:true});
  if(await closeWindow.isVisible()) await closeWindow.click();
  await expect(page.getByRole('button',{name:'수강신청 입장 →'})).toBeDisabled();
  await page.getByRole('button',{name:'지금 오픈하기',exact:true}).click();
  await page.getByText('개발자용 시연 설정',{exact:true}).click();
  await expect(page.getByRole('button',{name:'수강신청 입장 →'})).toBeEnabled();
  await page.screenshot({path:'test-results/gate-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'수강신청 입장 →'}).click();
  await expect(page.locator('tbody tr')).toHaveCount(24);
  await expect(page.getByRole('button',{name:'컴퓨터개론 정원 마감',exact:true})).toBeDisabled();
  await page.getByPlaceholder('강의명, 강의 코드, 교수명 검색').fill('CS102');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button',{name:'프로그래밍 기초 신청',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('수강신청이 완료되었습니다.');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button',{name:'프로그래밍 기초 신청 취소',exact:true})).toBeVisible();
  await page.getByRole('button',{name:/내 신청 내역/}).click();
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.reload();
  await expect(page.getByRole('button',{name:'프로그래밍 기초 신청 취소',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'로그아웃',exact:true}).click();
  await expect(page.getByRole('heading',{name:'로그인',exact:true})).toBeVisible();
  const other=`other-${Date.now()}@example.test`;
  expect((await request.post('/api/v1/auth/signup',{data:{name:'다른계정',email:other,password}})).status()).toBe(201);
  await login(other);
  await page.getByRole('button',{name:'수강신청 입장 →'}).click();
  await expect(page.getByRole('button',{name:'프로그래밍 기초 정원 마감',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:/내 신청 내역/}).click();
  await expect(page.getByText('신청 내역이 없습니다',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'로그아웃',exact:true}).click();
  await login(email);
  await page.getByRole('button',{name:'수강신청 입장 →'}).click();
  await page.getByRole('button',{name:'프로그래밍 기초 신청 취소',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('신청 취소가 완료되었습니다.');
  await page.getByRole('button',{name:'확인',exact:true}).click();
  await expect(page.getByRole('button',{name:'프로그래밍 기초 신청',exact:true})).toBeEnabled();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'test-results/courses-mobile.png',fullPage:true});
  await expect(page.getByRole('heading',{name:'수강신청',exact:true})).toBeVisible();
});
